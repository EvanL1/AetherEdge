//! Canonical SQLite schema for AetherEdge.
//!
//! Owns the DDL constants, revision/integrity triggers and bootstrap helpers
//! that define the on-disk schema. This is the single source of truth: service
//! startup paths, `aether-config` re-exports and the `aether` CLI all read
//! these definitions, and tests use the same `init_*_schema` helpers so that
//! fixtures cannot drift from production DDL.
//!
//! The five IO tables are derived from the private record structs below rather
//! than written out by hand. `aether-config` previously carried a second,
//! generated copy of the same five tables and the two had drifted: the
//! hand-written text had dropped `NOT NULL` from every `scale`, `offset` and
//! `reverse` column, so `aether sync` provisioned a laxer schema than the one
//! `aether-io`'s tests ran against. Keeping the derivation here is what makes
//! that class of drift unrepresentable.
//!
//! # Usage
//!
//! ```rust,ignore
//! use common::schema;
//! use sqlx::SqlitePool;
//!
//! let pool = SqlitePool::connect("sqlite::memory:").await?;
//! schema::init_io_schema(&pool).await?;
//! ```

