/// Channels table record
/// Stores channel configurations - Maps to ChannelConfig structure
#[allow(dead_code)]
#[derive(Schema)]
#[table(
    name = "channels",
    suffix = "CHECK (TYPEOF(revision) = 'integer' AND revision >= 1), CHECK (channel_id >= 1 AND channel_id < 10000)"
)]
struct ChannelRecord {
    #[column(primary_key)]
    channel_id: u32,

    #[column(not_null, unique)]
    name: String,

    protocol: Option<String>,

    #[column(default = "false")]
    enabled: bool,

    config: Option<String>, // JSON TEXT

    /// Monotonic desired-state revision. Every authoritative writer must
    /// advance this value explicitly.
    #[column(default = "1")]
    revision: i64,

    #[column(default = "CURRENT_TIMESTAMP")]
    created_at: String, // TIMESTAMP type

    #[column(default = "CURRENT_TIMESTAMP")]
    updated_at: String, // TIMESTAMP type
}

